#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const dataDir = path.join(root, "docs", "site-data");
const rootDataDir = path.join(root, "site-data");
const outputPaths = [
  path.join(root, "cvpr-data.js"),
  path.join(root, "docs", "cvpr-data.js"),
];
const days = ["day1", "day2", "day3"];

const data = {};
for (const day of days) {
  const inputPath = path.join(dataDir, `cvpr_${day}.json`);
  const rootInputPath = path.join(rootDataDir, `cvpr_${day}.json`);
  const raw = fs.readFileSync(inputPath, "utf8").trim();
  const rootRaw = fs.readFileSync(rootInputPath, "utf8").trim();
  if (raw !== rootRaw) {
    throw new Error(`${path.relative(root, inputPath)} differs from ${path.relative(root, rootInputPath)}`);
  }
  data[day] = raw ? JSON.parse(raw) : [];
}

const output = [
  "// Generated by scripts/build-cvpr-static-data.js.",
  "// Do not edit by hand; update docs/site-data/cvpr_day*.json and rerun this script.",
  `window.CVPR_DATA = ${JSON.stringify(data)};`,
  "",
].join("\n");

for (const outputPath of outputPaths) {
  fs.writeFileSync(outputPath, output);
  console.log(`Wrote ${path.relative(root, outputPath)}`);
}
