#!/usr/bin/env python3
"""compare_policies_synthetic.py

Compare mean curves across policies and export camera-ready plots + LaTeX tables.

Expected directory layout:
  rootdir/
    eig/
      *_logs.json      # each file is a LIST of dicts, one dict per round
    uncertainty/
      *_logs.json
    random/
      *_logs.json

Outputs:
  rootdir/compare_<metric>.png
  rootdir/compare_<metric>.pdf
  rootdir/compare_<metric>.tex   # NEW: table matching the plotted curves
"""

import argparse
import glob
import json
import os

import numpy as np

import matplotlib
matplotlib.use("Agg")
import matplotlib as mpl
import matplotlib.pyplot as plt

from typing import List
# -----------------------------
# Policy name aliases (editable)
# -----------------------------
POLICY_ALIASES = {
    "eig": "CaPE",
    "uncertainty": "UNC",
    "random": "RND",
    "static_eig": "STE",
    "static_uncertainty": "STU",
    "static_random": "STR",
}

# Colorblind-safe palette (Okabe–Ito-ish)
# POLICY_COLORS = {
#     "eig": "#0072B2",          # blue
#     "uncertainty": "#E69F00",  # orange
#     "random": "#999999",       # gray
# }
POLICY_COLORS = {
    # Adaptive methods
    "eig": "#0072B2",                 # CaPE – strong blue
    "uncertainty": "#E69F00",          # UNC – strong orange

    # Static baselines (same hues, lighter)
    "static_eig": "#56B4E9",           # light blue
    "static_uncertainty": "#F0E442",   # light yellow/orange

    # Random baselines
    "random": "#999999",               # dark gray
    "static_random": "#CCCCCC",        # light gray
}

def apply_mpl_style(font_size: int, line_width: float) -> None:
    """Apply global matplotlib settings for camera-ready figures."""
    mpl.rcParams.update({
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
        "axes.linewidth": 1.5,
        "xtick.major.width": 1.2,
        "ytick.major.width": 1.2,
        "xtick.major.size": 5,
        "ytick.major.size": 5,
        "legend.frameon": False,
    })
    mpl.rcParams["font.size"] = font_size
    mpl.rcParams["lines.linewidth"] = line_width


def load_runs(outdir: str):
    """Load all *_logs.json under a policy directory. Each file is a list-of-dicts."""
    runs = []
    for path in sorted(glob.glob(os.path.join(outdir, "*_logs.json"))):
        with open(path, "r") as f:
            logs = json.load(f)
        if isinstance(logs, list):
            runs.append(logs)
    return runs


def average_metric(runs, key):
    """Compute mean/std across runs for a given metric key (trim to shortest run)."""
    minT = min(len(logs) for logs in runs)
    curves = np.array(
        [[row.get(key, np.nan) for row in logs[:minT]] for logs in runs],
        dtype=float
    )
    mean = np.nanmean(curves, axis=0)
    std = np.nanstd(curves, axis=0)
    return mean, std, minT


def _fmt_pm(mean_val: float, std_val: float, digits: int) -> str:
    """Format as 'm \\pm s' with fixed decimals, LaTeX-safe."""
    if np.isnan(mean_val) or np.isnan(std_val):
        return "--"
    fmt = f"{{:.{digits}f}}"
    return f"{fmt.format(mean_val)} $\\pm$ {fmt.format(std_val)}"


def write_latex_table(
    outpath_tex: str,
    metric_key: str,
    ylabel: str,
    policies,
    per_policy_stats,
    table_every: int,
    digits: int,
):
    """
    Writes a LaTeX table matching the plotted mean±std curves.
    per_policy_stats: dict policy -> (mean[T], std[T], T)
    """
    # Determine T = min across available policies (matching plotting trim logic)
    Ts = [per_policy_stats[p][2] for p in policies if p in per_policy_stats]
    if not Ts:
        return
    T = min(Ts)

    # Round indices (1..T), optionally subsampled
    rounds = list(range(1, T + 1, max(1, table_every)))
    if rounds[-1] != T:
        rounds.append(T)  # always include final round

    # Column spec: 1 for round + one per policy
    colspec = "r" + " " + " ".join(["c"] * len(policies))

    lines = []
    lines.append("% Auto-generated by compare_policies_synthetic.py")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append(f"\\caption{{Per-round mean $\\pm$ std for {ylabel} ({metric_key}) across runs.}}")
    lines.append(f"\\label{{tab:compare_{metric_key}}}")
    lines.append(f"\\begin{{tabular}}{{{colspec}}}")
    lines.append("\\toprule")

    # Header
    header_pols = [POLICY_ALIASES.get(p, p) for p in policies]
    lines.append("Round & " + " & ".join(header_pols) + " \\\\")
    lines.append("\\midrule")

    for r in rounds:
        row_cells = [str(r)]
        idx = r - 1
        for p in policies:
            if p not in per_policy_stats:
                row_cells.append("--")
                continue
            mean, std, _ = per_policy_stats[p]
            row_cells.append(_fmt_pm(float(mean[idx]), float(std[idx]), digits))
        lines.append(" & ".join(row_cells) + " \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    with open(outpath_tex, "w") as f:
        f.write("\n".join(lines))


def plot_compare_policies(
    indir: str,
    policies: List[str],
    outdir: str,
    outbase: str,
    max_round: int,
    font_size: int,
    line_width: float,
    dpi: int,
    table_every: int,
    table_digits: int,
    fig_width: int = 6,
    fig_height: int = 4,
):
    # NOTE: No titles (per request). Labels only.
    metrics = [
        ("avg_pred_entropy", "Entropy"),
        ("exp_true_class_prob", "ETCP"),
        ("brier", "Brier"),
        ("samp_skel_f1", "Skeleton F1"),
        ("samp_orient_f1", "Orientation F1"),
        ("samp_shd", "SHD"),
    ]

    for key, ylabel in metrics:
        plt.figure(figsize=(fig_width, fig_height))

        plt.tight_layout(pad=0.15)
        plt.locator_params(axis="x", nbins=5)
        plt.locator_params(axis="y", nbins=4)

        # Collect stats for LaTeX table (mean/std/minT) per policy
        per_policy_stats = {}

        for pol in policies:
            runs = load_runs(os.path.join(indir, pol))
            if not runs:
                print("Warning: No runs for ", pol)
                continue

            mean, std, minT = average_metric(runs, key)
            per_policy_stats[pol] = (mean, std, minT)

            rounds = np.arange(1, len(mean) + 1)
            color = POLICY_COLORS.get(pol, None)
            label = POLICY_ALIASES.get(pol, pol)

            rounds = rounds[:max_round]
            std = std[:max_round]
            mean = mean[:max_round]

            plt.fill_between(
                rounds, mean - std, mean + std,
                alpha=0.2, color=color, linewidth=0
            )
            plt.plot(
                rounds, mean,
                label=label,
                color=color,
                linewidth=line_width,
            )

        plt.xlabel("Round", fontsize=font_size)
        plt.ylabel(ylabel, fontsize=font_size)
        plt.xticks(fontsize=font_size)
        plt.yticks(fontsize=font_size)
        plt.legend(fontsize=font_size)
        plt.tight_layout()

        # Save plots
        plt.savefig(f"{outbase}_{key}.png", dpi=dpi)
        plt.savefig(f"{outbase}_{key}.pdf")
        plt.close()
        print("Saved", f"{outbase}_{key}.png/.pdf")

        # Save LaTeX table matching the plotted data
        out_tex = f"{outbase}_{key}.tex"
        write_latex_table(
            outpath_tex=out_tex,
            metric_key=key,
            ylabel=ylabel,
            policies=policies,
            per_policy_stats=per_policy_stats,
            table_every=table_every,
            digits=table_digits,
        )
        print("Saved", out_tex)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--indir", required=True,
        help="Directory containing subdirs per policy (eig/, random/, uncertainty/)"
    )
    ap.add_argument(
        "--outdir", required=True,
        help="Directory to contain output figures and tables"
    )

    ap.add_argument(
        "--policies", nargs="+",
        default=["eig", "uncertainty", "random"],
        help="List of policies to compare"
    )
    ap.add_argument(
        "--font_size", type=int, default=20,
        help="Base font size for camera-ready plots"
    )
    ap.add_argument(
        "--line_width", type=float, default=3.5,
        help="Line width for camera-ready plots"
    )
    ap.add_argument(
        "--dpi", type=int, default=200,
        help="DPI for PNG outputs"
    )
    ap.add_argument(
        "--table_every", type=int, default=1,
        help="Write every k-th round to the LaTeX table (1 = all rounds)."
    )
    ap.add_argument(
        "--table_digits", type=int, default=3,
        help="Number of decimal places in LaTeX tables."
    )
    ap.add_argument(
        "--max_round", type=int, default=190,
        help="Maximum number of rounds to compare."
    )

    ap.add_argument("--fig_width", type=float, default=6)
    ap.add_argument("--fig_height", type=float, default=6)

    args = ap.parse_args()

    apply_mpl_style(args.font_size, args.line_width)

    os.makedirs(args.outdir, exist_ok=True)
    outbase = os.path.join(args.outdir, "compare")
    plot_compare_policies(
        indir=args.indir,
        outdir=args.outdir,
        policies=args.policies,
        max_round=args.max_round,
        outbase=outbase,
        font_size=args.font_size,
        line_width=args.line_width,
        dpi=args.dpi,
        table_every=args.table_every,
        table_digits=args.table_digits,
        fig_width=args.fig_width,
        fig_height=args.fig_height,
    )


if __name__ == "__main__":
    main()

