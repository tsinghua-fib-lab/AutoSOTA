"""
Disagreement-Aware Evaluation Model using Expectation-Maximization.

This module implements:
1. Dawid-Skene model (Hard initialization from majority vote)
2. Posterior Expected Credit (soft probabilistic scoring)

The model learns:
- Per-annotator confusion matrices (how each annotator's labels relate to true labels)
- Per-item latent true label distributions
- Class prior probabilities
"""

import numpy as np
import pandas as pd
from typing import Dict, List, Optional, Tuple, Union
from collections import defaultdict
import warnings


class DisagreementModel:
    """
    Bayesian latent variable model for handling annotator disagreement.
    
    This model assumes:
    - Each item has a latent true label z_i
    - Each annotator r has a confusion matrix π_r[c_true, c_obs]
    - Labels are generated by annotators observing true labels through their confusion matrix
    
    The model uses EM to jointly learn:
    - The posterior distribution over true labels for each item (gamma)
    - The confusion matrix for each annotator (pi)
    - The prior distribution over classes (mu)
    """
    
    def __init__(
        self,
        n_classes: int = 2,
        dirichlet_prior: float = 1.01,
        max_iterations: int = 100,
        convergence_threshold: float = 1e-6,
        verbose: bool = True
    ):
        """
        Initialize the disagreement model.
        
        Args:
            n_classes: Number of possible labels (2 for binary, 3 for ternary)
            dirichlet_prior: Dirichlet prior parameter for smoothing (β in the proposal)
            max_iterations: Maximum number of EM iterations
            convergence_threshold: Stop when max change in gamma < threshold
            verbose: Print progress information
        """
        self.n_classes = n_classes
        self.dirichlet_prior = dirichlet_prior
        self.adaptive_c = 0.0  # IDEA-11: adaptive prior strength (0=disabled)
        self.consistency_alpha = 0.0  # IDEA-02: annotator consistency weight (0=disabled)
        self.max_iterations = max_iterations
        self.convergence_threshold = convergence_threshold
        self.verbose = verbose
        
        # Model parameters (set after fitting)
        self.mu = None  # Class prior: P(true label = c)
        self.pi = None  # Annotator confusion matrices: {annotator: confusion_matrix}
        self.gamma = None  # Item posteriors: {item_id: P(true label = c | observations)}
        
        # Data mappings
        self.item_ids = None
        self.annotator_ids = None
        self.item_to_idx = None
        self.annotator_to_idx = None
        
        # Convergence tracking
        self.convergence_history = []
        
    def _prepare_data(self, df: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """
        Convert DataFrame to internal representation.
        
        Returns:
            item_indices: Array of item indices for each annotation
            annotator_indices: Array of annotator indices for each annotation
            labels: Array of observed labels
        """
        self.item_ids = df['item_id'].unique().tolist()
        self.annotator_ids = df['annotator_id'].unique().tolist()
        
        self.item_to_idx = {item: idx for idx, item in enumerate(self.item_ids)}
        self.annotator_to_idx = {ann: idx for idx, ann in enumerate(self.annotator_ids)}
        
        item_indices = df['item_id'].map(self.item_to_idx).values
        annotator_indices = df['annotator_id'].map(self.annotator_to_idx).values
        labels = df['label'].values
        
        
        # IDEA-11: compute per-annotator annotation counts for adaptive prior
        self.annotator_counts = {}
        for aidx in annotator_indices:
            self.annotator_counts[aidx] = self.annotator_counts.get(aidx, 0) + 1
        return item_indices, annotator_indices, labels
    
    def _build_observation_structure(
        self,
        item_indices: np.ndarray,
        annotator_indices: np.ndarray,
        labels: np.ndarray
    ) -> Dict:
        """
        Build efficient lookup structure for observations.
        
        Returns:
            Dictionary mapping item_idx to list of (annotator_idx, label) tuples
        """
        observations = defaultdict(list)
        for i_idx, a_idx, label in zip(item_indices, annotator_indices, labels):
            observations[i_idx].append((a_idx, label))
        return dict(observations)
    
    def _initialize_gamma_uniform(self, n_items: int) -> np.ndarray:
        """Initialize gamma uniformly."""
        return np.ones((n_items, self.n_classes)) / self.n_classes
    
    def _initialize_gamma_majority_vote(
        self,
        observations: Dict,
        n_items: int
    ) -> np.ndarray:
        """
        Initialize gamma using majority vote (Dawid-Skene hard initialization).
        
        This is the "hard" initialization where we start from majority vote
        and then refine with the EM algorithm.
        """
        gamma = np.zeros((n_items, self.n_classes))
        
        for item_idx in range(n_items):
            if item_idx in observations:
                # Count votes for each class
                votes = np.zeros(self.n_classes)
                for _, label in observations[item_idx]:
                    votes[label] += 1
                
                # Set gamma to majority vote (hard assignment)
                majority_class = np.argmax(votes)
                gamma[item_idx, majority_class] = 1.0
            else:
                # No observations - use uniform
                gamma[item_idx] = 1.0 / self.n_classes
        
        return gamma
    
    def _initialize_pi(self, n_annotators: int) -> np.ndarray:
        """
        Initialize annotator confusion matrices.
        
        Start with high diagonal (assume annotators are mostly correct).
        """
        # Initialize with 0.8 on diagonal, rest distributed uniformly
        pi = np.zeros((n_annotators, self.n_classes, self.n_classes))
        
        diagonal_weight = 0.8
        off_diagonal_weight = (1 - diagonal_weight) / (self.n_classes - 1)
        
        for r in range(n_annotators):
            for c in range(self.n_classes):
                for o in range(self.n_classes):
                    if c == o:
                        pi[r, c, o] = diagonal_weight
                    else:
                        pi[r, c, o] = off_diagonal_weight
        
        return pi
    
    def _e_step(
        self,
        observations: Dict,
        mu: np.ndarray,
        pi: np.ndarray,
        n_items: int
    ) -> np.ndarray:
        """
        E-step: Compute posterior distribution over true labels for each item.

        Formula: gamma_ic = P(z_i = c | {y_ir}) proportional to mu_c * prod_r pi_r[c, y_ir]

        IDEA-02: Optionally weights annotators by consistency quality.
        """
        gamma = np.zeros((n_items, self.n_classes))

        # Compute annotator quality from confusion matrices
        n_annotators = pi.shape[0]
        quality = np.array([np.diag(pi[r]).mean() for r in range(n_annotators)])
        mean_quality = quality.mean()

        for item_idx in range(n_items):
            if item_idx not in observations:
                gamma[item_idx] = mu.copy()
                continue

            # Compute unnormalized log-probabilities for numerical stability
            log_probs = np.log(mu + 1e-10)

            for annotator_idx, observed_label in observations[item_idx]:
                # IDEA-02: weight annotator by consistency
                if self.consistency_alpha > 0:
                    weight = 1.0 + self.consistency_alpha * (quality[annotator_idx] - mean_quality)
                else:
                    weight = 1.0

                # Add weighted log probability from this annotator
                for c in range(self.n_classes):
                    log_probs[c] += weight * np.log(pi[annotator_idx, c, observed_label] + 1e-10)

            # Normalize (softmax)
            log_probs -= np.max(log_probs)  # For numerical stability
            probs = np.exp(log_probs)
            gamma[item_idx] = probs / probs.sum()

        return gamma

    
    def _m_step(
        self,
        observations: Dict,
        gamma: np.ndarray,
        n_annotators: int
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        M-step: Update class prior and annotator confusion matrices.
        
        Update class prior: μ_c = (1/N) × Σ_i γ_ic
        
        Update confusion matrices: 
        π_r[c, o] = (Σ_{i: y_ir = o} γ_ic + β_o - 1) / (Σ_o' Σ_{i: y_ir = o'} γ_ic + β_o' - 1)
        """
        n_items = gamma.shape[0]
        
        # Update class prior
        mu = gamma.mean(axis=0)
        
        # Update annotator confusion matrices
        pi = np.zeros((n_annotators, self.n_classes, self.n_classes))
        
        # Build annotator-centric view of data
        annotator_observations = defaultdict(list)
        for item_idx, obs_list in observations.items():
            for annotator_idx, label in obs_list:
                annotator_observations[annotator_idx].append((item_idx, label))
        
        for annotator_idx in range(n_annotators):
            if annotator_idx not in annotator_observations:
                # No observations from this annotator - use prior
                pi[annotator_idx] = np.eye(self.n_classes)
                continue
            
            # Compute counts with Dirichlet prior
            for c in range(self.n_classes):
                # IDEA-11: adaptive Dirichlet prior based on annotation count
                if self.adaptive_c > 0:
                    n_ann = self.annotator_counts.get(annotator_idx, 1)
                    adaptive_prior = 1.0 + self.adaptive_c / (n_ann ** 0.5)
                    prior_val = max(adaptive_prior, 1.001)  # ensure > 1
                else:
                    prior_val = self.dirichlet_prior
                counts = np.full(self.n_classes, prior_val - 1)
                
                for item_idx, observed_label in annotator_observations[annotator_idx]:
                    counts[observed_label] += gamma[item_idx, c]
                
                # Normalize
                total = counts.sum()
                if total > 0:
                    pi[annotator_idx, c] = counts / total
                else:
                    pi[annotator_idx, c] = 1.0 / self.n_classes
        
        return mu, pi
    
    def fit(
        self,
        df: pd.DataFrame,
        initialization: str = 'majority_vote'
    ) -> 'DisagreementModel':
        """
        Fit the model using EM algorithm.
        
        Args:
            df: DataFrame with columns item_id, agent_id, annotator_id, label
            initialization: 'majority_vote' for Dawid-Skene (hard), 'uniform' for soft
            
        Returns:
            self (fitted model)
        """
        if self.verbose:
            print(f"Fitting disagreement model with {initialization} initialization...")
        
        # Prepare data
        item_indices, annotator_indices, labels = self._prepare_data(df)
        n_items = len(self.item_ids)
        n_annotators = len(self.annotator_ids)
        
        # Build observation structure
        observations = self._build_observation_structure(
            item_indices, annotator_indices, labels
        )
        
        # Initialize
        if initialization == 'majority_vote':
            gamma = self._initialize_gamma_majority_vote(observations, n_items)
        else:
            gamma = self._initialize_gamma_uniform(n_items)
        
        pi = self._initialize_pi(n_annotators)
        mu = gamma.mean(axis=0)
        
        if self.verbose:
            print(f"  Items: {n_items}, Annotators: {n_annotators}, Classes: {self.n_classes}")
        
        # EM iterations
        self.convergence_history = []
        
        for iteration in range(self.max_iterations):
            old_gamma = gamma.copy()
            
            # E-step
            gamma = self._e_step(observations, mu, pi, n_items)
            
            # M-step
            mu, pi = self._m_step(observations, gamma, n_annotators)
            
            # Check convergence
            max_change = np.abs(gamma - old_gamma).max()
            self.convergence_history.append(max_change)
            
            if self.verbose and (iteration + 1) % 10 == 0:
                print(f"  Iteration {iteration + 1}: max change = {max_change:.6f}")
            
            if max_change < self.convergence_threshold:
                if self.verbose:
                    print(f"  Converged after {iteration + 1} iterations")
                break
        
        # Store results
        self.mu = mu
        self.pi = {self.annotator_ids[i]: pi[i] for i in range(n_annotators)}
        self.gamma = {self.item_ids[i]: gamma[i] for i in range(n_items)}
        
        if self.verbose:
            print(f"  Final class prior: {mu}")
        
        return self
    
    def get_item_posteriors(self) -> pd.DataFrame:
        """
        Get posterior distribution over true labels for each item.
        
        Returns:
            DataFrame with item_id and probability columns for each class
        """
        if self.gamma is None:
            raise RuntimeError("Model not fitted. Call fit() first.")
        
        records = []
        for item_id, probs in self.gamma.items():
            record = {'item_id': item_id}
            for c in range(self.n_classes):
                record[f'p_class_{c}'] = probs[c]
            records.append(record)
        
        return pd.DataFrame(records)
    
    def get_annotator_confusion_matrices(self) -> Dict[str, np.ndarray]:
        """
        Get learned confusion matrices for each annotator.
        
        Returns:
            Dictionary mapping annotator_id to confusion matrix
        """
        if self.pi is None:
            raise RuntimeError("Model not fitted. Call fit() first.")
        
        return self.pi.copy()
    
    def get_annotator_quality_scores(self) -> pd.DataFrame:
        """
        Compute quality scores for each annotator based on their confusion matrices.
        
        Quality is measured as the average diagonal entry (accuracy when correct label is known).
        """
        if self.pi is None:
            raise RuntimeError("Model not fitted. Call fit() first.")
        
        records = []
        for annotator_id, cm in self.pi.items():
            accuracy = np.diag(cm).mean()
            
            # Compute bias metrics
            leniency = cm[:, -1].mean()  # Tendency to give highest label
            strictness = cm[:, 0].mean()  # Tendency to give lowest label
            
            records.append({
                'annotator_id': annotator_id,
                'accuracy': accuracy,
                'leniency': leniency,
                'strictness': strictness
            })
        
        return pd.DataFrame(records).sort_values('accuracy', ascending=False)


def compute_posterior_expected_credit(
    model: DisagreementModel,
    df: pd.DataFrame,
    class_values: Optional[Dict[int, float]] = None,
    temperature: float = 1.0
) -> pd.DataFrame:
    """
    Compute per-item scores using posterior expected credit.
    
    credit(i) = Σ_c γ_ic × value(c)
    
    Args:
        model: Fitted DisagreementModel
        df: Original DataFrame (needed for agent mapping)
        class_values: Mapping from class index to numeric value
        
    Returns:
        DataFrame with item_id, agent_id, and credit columns
    """
    if class_values is None:
        class_values = {c: c / (model.n_classes - 1) for c in range(model.n_classes)}
    
    # Get posteriors
    posteriors = model.get_item_posteriors()
    
    # Apply temperature scaling to gamma posteriors (IDEA-06)
    if temperature != 1.0:
        prob_cols = [f"p_class_{c}" for c in range(model.n_classes)]
        probs = posteriors[prob_cols].values
        eps = 1e-10
        log_probs = np.log(probs + eps)
        scaled_log_probs = log_probs / temperature
        scaled_log_probs -= scaled_log_probs.max(axis=1, keepdims=True)
        scaled_probs = np.exp(scaled_log_probs)
        scaled_probs /= scaled_probs.sum(axis=1, keepdims=True)
        for c in range(model.n_classes):
            posteriors[f"p_class_{c}"] = scaled_probs[:, c]
    
    # Compute expected credit
    posteriors['credit'] = 0.0
    for c in range(model.n_classes):
        posteriors['credit'] += posteriors[f'p_class_{c}'] * class_values[c]
    
    # Add agent mapping
    item_agent = df[['item_id', 'agent_id']].drop_duplicates()
    result = posteriors.merge(item_agent, on='item_id')
    
    return result


def compute_agent_scores_pec(
    model: DisagreementModel,
    df: pd.DataFrame,
    class_values: Optional[Dict[int, float]] = None,
    temperature: float = 1.0
) -> pd.DataFrame:
    """
    Compute agent scores using Posterior Expected Credit.
    
    Uses soft posteriors: score = Σ_c γ_ic × value(c)
    
    Args:
        model: Fitted DisagreementModel
        df: Original DataFrame with agent mapping
        class_values: Mapping from class index to numeric value
        
    Returns:
        DataFrame with agent_id, score, n_items
    """
    item_credits = compute_posterior_expected_credit(model, df, class_values, temperature)
    
    agent_scores = item_credits.groupby('agent_id').agg(
        score=('credit', 'mean'),
        n_items=('item_id', 'count')
    ).reset_index()
    
    return agent_scores.sort_values('score', ascending=False)


def compute_agent_scores_ds_hard(
    model: DisagreementModel,
    df: pd.DataFrame,
    class_values: Optional[Dict[int, float]] = None
) -> pd.DataFrame:
    """
    Compute agent scores using Dawid-Skene hard labels.
    
    Uses argmax of posteriors: score = value(argmax_c γ_ic)
    
    Args:
        model: Fitted DisagreementModel
        df: Original DataFrame with agent mapping
        class_values: Mapping from class index to numeric value
        
    Returns:
        DataFrame with agent_id, score, n_items
    """
    if class_values is None:
        class_values = {c: c / (model.n_classes - 1) for c in range(model.n_classes)}
    
    # Get posteriors
    posteriors = model.get_item_posteriors()
    
    # Get hard label (argmax) for each item
    prob_cols = [f'p_class_{c}' for c in range(model.n_classes)]
    posteriors['hard_label'] = posteriors[prob_cols].values.argmax(axis=1)
    posteriors['score'] = posteriors['hard_label'].map(class_values)
    
    # Add agent mapping
    item_agent = df[['item_id', 'agent_id']].drop_duplicates()
    result = posteriors.merge(item_agent, on='item_id')
    
    # Aggregate by agent
    agent_scores = result.groupby('agent_id').agg(
        score=('score', 'mean'),
        n_items=('item_id', 'count')
    ).reset_index()
    
    return agent_scores.sort_values('score', ascending=False)


def compute_item_ambiguity(model: DisagreementModel) -> pd.DataFrame:
    """
    Compute ambiguity score for each item.
    
    ambiguity(i) = 1 - max_c γ_ic
    
    Higher ambiguity means more uncertainty about the true label.
    """
    if model.gamma is None:
        raise RuntimeError("Model not fitted. Call fit() first.")
    
    records = []
    for item_id, probs in model.gamma.items():
        ambiguity = 1.0 - probs.max()
        predicted_class = probs.argmax()
        confidence = probs.max()
        
        records.append({
            'item_id': item_id,
            'ambiguity': ambiguity,
            'predicted_class': predicted_class,
            'confidence': confidence
        })
    
    return pd.DataFrame(records).sort_values('ambiguity', ascending=False)


def bootstrap_agent_scores_pec(
    df: pd.DataFrame,
    n_bootstrap: int = 1000,
    class_values: Optional[Dict[int, float]] = None,
    n_classes: int = 2,
    initialization: str = 'majority_vote',
    random_state: Optional[int] = None,
    verbose: bool = False
) -> pd.DataFrame:
    """
    Compute bootstrap confidence intervals for PEC agent scores.
    
    Args:
        df: DataFrame with annotation data
        n_bootstrap: Number of bootstrap samples
        class_values: Mapping from class index to numeric value
        n_classes: Number of classes
        initialization: 'majority_vote' or 'uniform'
        random_state: Random seed
        verbose: Print progress
        
    Returns:
        DataFrame with agent_id, score, ci_lower, ci_upper, std, n_items
    """
    if random_state is not None:
        np.random.seed(random_state)
    
    # Get unique items
    items = df['item_id'].unique()
    n_items = len(items)
    
    # Get agents
    agents = df['agent_id'].unique()
    bootstrap_scores = {agent: [] for agent in agents}
    
    # Fit base model
    base_model = DisagreementModel(n_classes=n_classes, verbose=False)
    base_model.fit(df, initialization=initialization)
    base_scores = compute_agent_scores_pec(base_model, df, class_values, temperature=1.0)
    
    for b in range(n_bootstrap):
        if verbose and (b + 1) % 100 == 0:
            print(f"  Bootstrap iteration {b + 1}/{n_bootstrap}")
        
        # Resample items
        sampled_items = np.random.choice(items, size=n_items, replace=True)
        # IDEA-09: proper bootstrap with replacement (concat per-item to preserve duplicates)
        dfs = [df[df['item_id'] == iid] for iid in sampled_items]
        sampled_df = pd.concat(dfs, ignore_index=True)
        
        # Fit model
        try:
            model = DisagreementModel(n_classes=n_classes, verbose=False)
            model.fit(sampled_df, initialization=initialization)
            scores = compute_agent_scores_pec(model, sampled_df, class_values, temperature=1.0)
            
            for _, row in scores.iterrows():
                bootstrap_scores[row['agent_id']].append(row['score'])
        except Exception:
            # Skip failed iterations
            pass
    
    # Compute confidence intervals
    results = []
    for _, row in base_scores.iterrows():
        agent = row['agent_id']
        bs_scores = bootstrap_scores[agent]
        
        if len(bs_scores) > 0:
            results.append({
                'agent_id': agent,
                'score': row['score'],
                'ci_lower': np.percentile(bs_scores, 2.5),
                'ci_upper': np.percentile(bs_scores, 97.5),
                'std': np.std(bs_scores),
                'n_items': row['n_items']
            })
    
    return pd.DataFrame(results).sort_values('score', ascending=False)


