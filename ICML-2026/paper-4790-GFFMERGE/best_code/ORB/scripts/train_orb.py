EV_TO_KCAL_MOL = 23.060547


def normalize_units(units: str) -> str:
    return units.strip().lower().replace(" ", "")


def resolve_data_unit_scale(units: str) -> float:
    key = normalize_units(units)
    if key in ("kcal/mol", "kcalmol", "kcal_per_mol", "kcalpermol", "kcal"):
        return KCAL_MOL_TO_EV
    if key in ("ev", "electronvolt", "electronvolts"):
        return 1.0
    raise ValueError(f"Unsupported data units '{units}'. Use 'kcal/mol' or 'eV'.")


def scale_batch_targets(batch: object, scale: float) -> None:
    if scale == 1.0:
        return
    node_targets = getattr(batch, "node_targets", None)
    if node_targets is not None and "forces" in node_targets:
        node_targets["forces"] = node_targets["forces"] * scale
    system_targets = getattr(batch, "system_targets", None)
    if system_targets is not None and "energy" in system_targets:
        system_targets["energy"] = system_targets["energy"] * scale
    graph_targets = getattr(batch, "graph_targets", None)
    if graph_targets is not None and "energy" in graph_targets:
        graph_targets["energy"] = graph_targets["energy"] * scale


