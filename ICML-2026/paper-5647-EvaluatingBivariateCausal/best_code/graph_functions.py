def greedy_fas(A: np.ndarray) -> List[Tuple[int, int]]:
    """
    Greedy Feedback Arc Set (FAS) algorithm.
    
    Given a directed graph, finds a set of edges whose removal makes the graph acyclic.
    Uses the greedy heuristic based on the difference between out-degree and in-degree.
    
    Algorithm:
    1. Iteratively process vertices, adding them to either the "left" or "right" sequence
    2. At each step, choose a vertex with maximum (out-degree - in-degree) for right,
       or minimum for left (i.e., sinks go left, sources go right)
    3. The final ordering is: left_sequence (reversed) + right_sequence
    4. Back edges (edges going from later to earlier in this order) form the FAS
    
    Parameters:
        A: Adjacency matrix where A[i,j] = 1 means edge i -> j
    
    Returns:
        fas: List of edges (i, j) that form the feedback arc set
    """
    n = A.shape[0]
    
    # Work with a copy to modify during algorithm
    adj = A.copy().astype(float)
    
    # Track remaining vertices
    remaining = set(range(n))
    
    # Sequences for building the final order
    s_left = []   # Will be reversed at the end
    s_right = []
    
    while remaining:
        # Find and remove sinks (vertices with out-degree 0)
        while True:
            sinks = [v for v in remaining if np.sum(adj[v, :]) == 0]
            if not sinks:
                break
            for v in sinks:
                s_left.append(v)
                remaining.remove(v)
                adj[:, v] = 0  # Remove incoming edges
        
        if not remaining:
            break
            
        # Find and remove sources (vertices with in-degree 0)
        while True:
            sources = [v for v in remaining if np.sum(adj[:, v]) == 0]
            if not sources:
                break
            for v in sources:
                s_right.append(v)
                remaining.remove(v)
                adj[v, :] = 0  # Remove outgoing edges
        
        if not remaining:
            break
        
        # Choose vertex with maximum (out-degree - in-degree)
        best_v = None
        best_delta = float('-inf')
        for v in remaining:
            out_deg = np.sum(adj[v, :])
            in_deg = np.sum(adj[:, v])
            delta = out_deg - in_deg
            if delta > best_delta:
                best_delta = delta
                best_v = v
        
        # Add to right sequence and remove from graph
        s_right.append(best_v)
        remaining.remove(best_v)
        adj[best_v, :] = 0
        adj[:, best_v] = 0
    
    # Build final ordering: reversed left + right
    ordering = list(reversed(s_left)) + s_right
    
    # Create position map for the ordering
    position = {v: i for i, v in enumerate(ordering)}
    
    # Find back edges (edges going from later to earlier in ordering)
    fas = []
    for i in range(n):
        for j in range(n):
            if A[i, j] > 0:  # There is an edge i -> j
                if position[i] > position[j]:  # i comes after j in ordering
                    fas.append((i, j))
    
    return fas


def is_acyclic(A: np.ndarray) -> bool:
    """
    Check if a directed graph (given as adjacency matrix) is acyclic.
    
    Uses the property that a DAG has a topological ordering, which can be
    found by repeatedly removing vertices with no incoming edges.
    
    Parameters:
        A: Adjacency matrix where A[i,j] = 1 means edge i -> j
    
    Returns:
        True if the graph is acyclic, False otherwise
    """
    n = A.shape[0]
    adj = A.copy().astype(float)
    remaining = set(range(n))
    
    while remaining:
        # Find vertices with no incoming edges from remaining vertices
        sources = []
        for v in remaining:
            in_deg = sum(adj[u, v] for u in remaining)
            if in_deg == 0:
                sources.append(v)
        
        if not sources:
            # No source found but vertices remain -> cycle exists
            return False
        
        # Remove one source
        v = sources[0]
        remaining.remove(v)
    
    return True


def remove_edges(A: np.ndarray, edges: List[Tuple[int, int]]) -> np.ndarray:
    """
    Remove a set of edges from an adjacency matrix.
    
    Parameters:
        A: Adjacency matrix
        edges: List of edges (i, j) to remove
    
    Returns:
        New adjacency matrix with edges removed
    """
    A_new = A.copy()
    for i, j in edges:
        A_new[i, j] = 0
    return A_new


def transitive_closure(A: np.ndarray) -> np.ndarray:
    """
    Compute the transitive closure of an acyclic directed graph.
    
    For a DAG with adjacency matrix A, the transitive closure is computed as:
        tc(A) = (I - A)^{-1} - I
    
    The resulting matrix has entry [i,j] = 1 if there is a directed path from i to j.
    
    Parameters:
        A: Adjacency matrix of a DAG where A[i,j] = 1 means edge i -> j
    
    Returns:
        tc_adj: Adjacency matrix of the transitive closure (binary, no self-loops)
    """
    n = A.shape[0]
    I = np.eye(n)
    
    # (I - A)^{-1} gives the reachability matrix
    # Entry [i,j] counts number of paths from i to j (including length 0 path i to i)
    I_minus_A_inv = np.linalg.inv(I - A)
    
    # Subtract I to remove self-loops, then binarize
    tc_adj = (np.abs(I_minus_A_inv - I) > 1e-10).astype(int)
    
    return tc_adj


def count_tc_edges(A: np.ndarray) -> int:
    """
    Count the number of edges in the transitive closure of a DAG.
    
    Parameters:
        A: Adjacency matrix of a DAG
    
    Returns:
        Number of edges in the transitive closure
    """
    tc = transitive_closure(A)
    return int(np.sum(tc))


def greedy_transitivity_editing(A: np.ndarray, verbose: bool = False) -> Tuple[List[Tuple[int, int]], List[Tuple[int, int]]]:
    """
    Greedy Transitivity Editing (GreedyTE) algorithm.
    
    Takes an acyclic directed graph and computes a set of edge deletions and additions
    that transform it into a transitively closed graph.
    
    The algorithm greedily removes edges that maximize the reduction in transitive
    closure size, then adds all edges needed to complete the transitive closure.
    
    Algorithm:
        1. Initialize H = D (input graph)
        2. Repeat:
           - For each edge e in H, compute gain = |tc(H)| - |tc(H \ e)| - 1
           - If best gain > 0, remove the best edge and add it to E_del
        3. Until no positive gain
        4. E_add = tc(D \ E_del) \ (D \ E_del)
        5. Return (E_del, E_add)
    
    Parameters:
        A: Adjacency matrix of an acyclic directed graph where A[i,j] = 1 means edge i -> j
        verbose: If True, print progress information
    
    Returns:
        E_del: List of edges to delete from the original graph
        E_add: List of edges to add to achieve transitive closure
    """
    n = A.shape[0]
    
    # Verify input is acyclic
    if not is_acyclic(A):
        raise ValueError("Input graph must be acyclic")
    
    # Initialize
    E_del = []
    H = A.copy().astype(float)
    
    iteration = 0
    while True:
        iteration += 1
        
        # Current edges in H
        current_edges = [(i, j) for i in range(n) for j in range(n) if H[i, j] > 0]
        
        if not current_edges:
            break
        
        # Compute |tc(H)|
        tc_H_size = count_tc_edges(H)
        
        # Find best edge to remove
        best_gain = 0
        e_star = None
        
        for e in current_edges:
            i, j = e
            # Create H \ e
            H_minus_e = H.copy()
            H_minus_e[i, j] = 0
            
            # Compute |tc(H \ e)|
            tc_H_minus_e_size = count_tc_edges(H_minus_e)
            
            # Gain = |tc(H)| - |tc(H \ e)| - 1
            gain = tc_H_size - tc_H_minus_e_size - 1
            
            if gain > best_gain:
                best_gain = gain
                e_star = e
        
        if verbose:
            print(f"Iteration {iteration}: |H| = {len(current_edges)} edges, |tc(H)| = {tc_H_size}, best_gain = {best_gain}")
        
        if best_gain > 0:
            E_del.append(e_star)
            H[e_star[0], e_star[1]] = 0
            if verbose:
                print(f"  -> Removed edge {e_star}")
        else:
            break
    
    # D' = D \ E_del (original graph with deleted edges removed)
    D_prime = remove_edges(A, E_del)
    
    # E_add = tc(D') \ D'
    tc_D_prime = transitive_closure(D_prime)
    
    E_add = []
    for i in range(n):
        for j in range(n):
            # Edge is in tc(D') but not in D'
            if tc_D_prime[i, j] > 0 and D_prime[i, j] == 0:
                E_add.append((i, j))
    
    if verbose:
        print(f"\nResult: {len(E_del)} deletions, {len(E_add)} additions")
        print(f"  E_del = {E_del}")
        print(f"  E_add = {E_add}")
    
    return E_del, E_add


def apply_transitivity_editing(A: np.ndarray, E_del: List[Tuple[int, int]], 
                                E_add: List[Tuple[int, int]]) -> np.ndarray:
    """
    Apply transitivity editing operations to create the transitively closed graph.
    
    Parameters:
        A: Original adjacency matrix
        E_del: Edges to delete
        E_add: Edges to add
    
    Returns:
        Adjacency matrix of the transitively closed graph
    """
    result = A.copy()
    
    # Remove deleted edges
    for i, j in E_del:
        result[i, j] = 0
    
    # Add new edges
    for i, j in E_add:
        result[i, j] = 1
    
    return result


def is_transitively_closed(A: np.ndarray) -> bool:
    """
    Check if a directed graph is transitively closed.
    
    A graph is transitively closed if for any path i -> ... -> j, the edge i -> j exists.
    
    Parameters:
        A: Adjacency matrix
    
    Returns:
        True if the graph is transitively closed
    """
    tc = transitive_closure(A)
    
    # Check if A contains all edges in its transitive closure
    for i in range(A.shape[0]):
        for j in range(A.shape[0]):
            if tc[i, j] > 0 and A[i, j] == 0:
                return False
    
    return True


