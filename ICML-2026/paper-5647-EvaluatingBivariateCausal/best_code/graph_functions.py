import numpy as np
import matplotlib.pyplot as plt
import networkx as nx
from typing import Tuple, Set, List


def generate_random_dag(n: int, m: int, p: float, seed: int = None) -> Tuple[np.ndarray, np.ndarray, Set[int]]:
    """
    Generate a random DAG on n+m variables with a random subset of m hidden variables.
    
    The DAG is generated by:
    1. Sampling a random permutation of n+m variables (defines topological order)
    2. For each pair (i, j) where i comes before j in the permutation,
       adding a directed edge i -> j with probability p
    3. Marking a random subset of m variables as "hidden"
    
    Parameters:
        n: Number of observed variables
        m: Number of hidden variables
        p: Probability of including each edge consistent with the topological order
        seed: Random seed for reproducibility
    
    Returns:
        adjacency_matrix: (n+m) x (n+m) adjacency matrix where A[i,j] = 1 means edge i -> j
        permutation: The random permutation used (topological order)
        hidden_variables: Set of indices of hidden variables
    """
    if seed is not None:
        np.random.seed(seed)
    
    total_vars = n + m
    
    # Step 1: Sample a random permutation (defines topological order)
    permutation = np.random.permutation(total_vars)
    
    # Step 2: Create adjacency matrix by sampling edges consistent with permutation
    # For each pair (i, j) where permutation places i before j, add edge with probability p
    adjacency_matrix = np.zeros((total_vars, total_vars), dtype=int)
    
    for idx_i in range(total_vars):
        for idx_j in range(idx_i + 1, total_vars):
            # permutation[idx_i] comes before permutation[idx_j] in topological order
            source = permutation[idx_i]
            target = permutation[idx_j]
            
            # Sample edge with probability p
            if np.random.random() < p:
                adjacency_matrix[source, target] = 1
    
    # Step 3: Sample a random subset of m variables to be hidden
    hidden_indices = np.random.choice(total_vars, size=m, replace=False)
    hidden_variables = set(hidden_indices)
    
    return adjacency_matrix, permutation, hidden_variables


def get_observed_variables(total_vars: int, hidden_variables: Set[int]) -> Set[int]:
    """
    Get the set of observed (non-hidden) variables.
    
    Parameters:
        total_vars: Total number of variables
        hidden_variables: Set of hidden variable indices
    
    Returns:
        Set of observed variable indices
    """
    return set(range(total_vars)) - hidden_variables


def compute_statement_graph(A: np.ndarray, hidden_variables: Set[int]) -> Tuple[np.ndarray, np.ndarray]:
    """
    Compute the statement graph from an adjacency matrix and hidden variables.
    
    The statement graph describes causal relationships between observed variables,
    marginalizing over hidden variables. It is described by two adjacency matrices:
    
    1. Directed edges: There is a directed edge i -> j if there is a directed path
       from i to j in the original graph. Computed as (I - A)^{-1}
    
    2. Bidirected edges: The confounding path closure of the statement graph.
       First we compute the initial confounding from hidden common ancestors in the
       original DAG, then we compute the full confounding path closure with respect
       to the statement graph's directed edges.
    
    Parameters:
        A: Adjacency matrix of the DAG where A[i,j] = 1 means edge i -> j
        hidden_variables: Set of indices of hidden variables
    
    Returns:
        directed_adj: Adjacency matrix of directed edges (between observed variables)
        bidirected_adj: Adjacency matrix of bidirected edges (between observed variables)
        observed: List of observed variable indices
    """
    n = A.shape[0]
    
    # Compute (I - A)^{-1} which gives the reachability/path matrix
    I = np.eye(n)
    I_minus_A_inv = np.linalg.inv(I - A)
    
    # Directed edges: (I - A)^{-1}
    # Entry [i,j] > 0 indicates there is a directed path from i to j
    directed_full = I_minus_A_inv
    
    # Extract only the observed variables
    observed = sorted(set(range(n)) - hidden_variables)
    observed_idx = np.array(observed)
    
    # Submatrix for observed variables only (directed edges)
    directed_adj = directed_full[np.ix_(observed_idx, observed_idx)]
    
    # Convert to binary adjacency (threshold at > 0 for paths)
    # For directed: remove self-loops (diagonal)
    directed_adj = (np.abs(directed_adj) > 1e-10).astype(float)
    np.fill_diagonal(directed_adj, 0)
    
    # Bidirected edges: 
    # Step 1: Compute initial confounding from hidden common ancestors in original DAG
    bidirected_full = np.zeros((n, n))
    confounding_full = compute_confounding_paths(A, bidirected_full)
    
    # Extract submatrix for observed variables only
    initial_bidirected = confounding_full[np.ix_(observed_idx, observed_idx)]
    
    # Step 2: Compute the confounding path closure with respect to the statement graph's
    # directed edges. This ensures the bidirected edges are closed under the statement
    # graph structure.
    bidirected_adj = compute_confounding_paths(directed_adj, initial_bidirected)
    
    return directed_adj, bidirected_adj, observed


def compute_confounding_paths(directed_adj: np.ndarray, bidirected_adj: np.ndarray) -> np.ndarray:
    """
    Compute the confounding path matrix for a graph with directed and bidirected edges.
    
    A confounding path between i and j is a path of the form:
        i <- ... <- H -> ... -> j
    where H is a common ancestor (possibly through bidirected edges), and critically:
    - The path from H to i does NOT go through j
    - The path from H to j does NOT go through i
    
    Algorithm:
    1. For each bidirected edge, introduce a new latent vertex l and replace 
       the bidirected edge with directed edges l -> i and l -> j
    2. For each pair (i, j), compute the confounding entry using:
       ((I - A')^{-T} - I) @ ((I - A'')^{-1} - I)[i, j]
       where A' has all edges incident to j removed, and A'' has all edges 
       incident to i removed
    
    Parameters:
        directed_adj: n x n adjacency matrix for directed edges (A[i,j] = 1 means i -> j)
        bidirected_adj: n x n symmetric adjacency matrix for bidirected edges 
                        (B[i,j] = B[j,i] = 1 means i <-> j)
    
    Returns:
        confounding_matrix: n x n matrix where entry [i,j] > 0 indicates a confounding
                           path exists between i and j
    """
    n = directed_adj.shape[0]
    
    # Count bidirected edges (upper triangular to avoid double counting)
    bidirected_edges = []
    for i in range(n):
        for j in range(i + 1, n):
            if bidirected_adj[i, j] > 0:
                bidirected_edges.append((i, j))
    
    num_latent = len(bidirected_edges)
    total_vars = n + num_latent
    
    # Build expanded adjacency matrix C
    C = np.zeros((total_vars, total_vars))
    
    # Copy original directed edges
    C[:n, :n] = directed_adj
    
    # For each bidirected edge i <-> j, add latent vertex l with edges l -> i, l -> j
    for idx, (bi, bj) in enumerate(bidirected_edges):
        l = n + idx  # Index of new latent vertex
        C[l, bi] = 1  # l -> bi
        C[l, bj] = 1  # l -> bj
    
    # Compute confounding matrix entry-by-entry
    # For each pair (i, j): use A' (edges to j removed) and A'' (edges to i removed)
    confounding_matrix = np.zeros((n, n))
    I = np.eye(total_vars)
    
    for i in range(n):
        for j in range(n):
            if i == j:
                continue
            
            # Create A' = C with all edges incident to j removed
            # (both incoming: k -> j, and outgoing: j -> k)
            A_prime = C.copy()
            A_prime[:, j] = 0  # Remove all incoming edges to j
            A_prime[j, :] = 0  # Remove all outgoing edges from j
            
            # Create A'' = C with all edges incident to i removed
            A_double_prime = C.copy()
            A_double_prime[:, i] = 0  # Remove all incoming edges to i
            A_double_prime[i, :] = 0  # Remove all outgoing edges from i
            
            # Compute ((I - A')^{-T} - I) @ ((I - A'')^{-1} - I)[i, j]
            I_minus_Ap_inv = np.linalg.inv(I - A_prime)
            I_minus_App_inv = np.linalg.inv(I - A_double_prime)
            
            # Left factor: (I - A')^{-T} - I, we need row i
            left_factor = I_minus_Ap_inv.T - I
            # Right factor: (I - A'')^{-1} - I, we need column j
            right_factor = I_minus_App_inv - I
            
            # Compute entry [i, j] of the product
            confounding_matrix[i, j] = left_factor[i, :] @ right_factor[:, j]
    
    # Binarize and clean up
    confounding_matrix = (np.abs(confounding_matrix) > 1e-10).astype(float)
    np.fill_diagonal(confounding_matrix, 0)
    
    return confounding_matrix


def count_cpc_edges(directed_adj: np.ndarray, bidirected_adj: np.ndarray) -> int:
    """
    Count the number of edges in the confounding path closure.
    
    Since the confounding matrix is symmetric, we count only upper triangular entries.
    
    Parameters:
        directed_adj: Adjacency matrix for directed edges
        bidirected_adj: Adjacency matrix for bidirected edges
    
    Returns:
        Number of edges in the confounding path closure
    """
    cpc = compute_confounding_paths(directed_adj, bidirected_adj)
    # Count upper triangular entries (since symmetric)
    n = cpc.shape[0]
    count = 0
    for i in range(n):
        for j in range(i + 1, n):
            if cpc[i, j] > 0:
                count += 1
    return count


def remove_bidirected_edge(bidirected_adj: np.ndarray, i: int, j: int) -> np.ndarray:
    """
    Remove a bidirected edge from the bidirected adjacency matrix.
    
    Parameters:
        bidirected_adj: Symmetric adjacency matrix for bidirected edges
        i, j: Indices of the edge to remove
    
    Returns:
        New bidirected adjacency matrix with edge removed
    """
    B_new = bidirected_adj.copy()
    B_new[i, j] = 0
    B_new[j, i] = 0
    return B_new


def greedy_confounding_path_closure(directed_adj: np.ndarray, bidirected_adj: np.ndarray, 
                                     verbose: bool = False) -> Tuple[List[Tuple[int, int]], List[Tuple[int, int]]]:
    """
    Greedy Confounding Path Closure (GreedyCPC) algorithm.
    
    Takes a mixed graph with directed and bidirected edges and computes a set of 
    bidirected edge deletions and additions that make the bidirected edge adjacency 
    matrix equal to the confounding path matrix.
    
    The algorithm greedily removes bidirected edges that maximize the reduction in 
    confounding path closure size, then adds all edges needed to complete the closure.
    
    Algorithm:
        1. Initialize H = G (input graph)
        2. Repeat:
           - For each bidirected edge e in H, compute gain = |cpc(H)| - |cpc(H \ e)| - 1
           - If best gain > 0, remove the best edge and add it to B_del
        3. Until no positive gain
        4. B_add = cpc(G \ B_del) \ B(G \ B_del)
        5. Return (B_del, B_add)
    
    Parameters:
        directed_adj: n x n adjacency matrix for directed edges (A[i,j] = 1 means i -> j)
        bidirected_adj: n x n symmetric adjacency matrix for bidirected edges
        verbose: If True, print progress information
    
    Returns:
        B_del: List of bidirected edges to delete (as tuples (i, j) with i < j)
        B_add: List of bidirected edges to add to achieve confounding path closure
    """
    n = directed_adj.shape[0]
    
    # Initialize
    B_del = []
    H_directed = directed_adj.copy().astype(float)
    H_bidirected = bidirected_adj.copy().astype(float)
    
    iteration = 0
    while True:
        iteration += 1
        
        # Current bidirected edges in H (upper triangular to avoid duplicates)
        current_bidirected = [(i, j) for i in range(n) for j in range(i + 1, n) 
                              if H_bidirected[i, j] > 0]
        
        if not current_bidirected:
            break
        
        # Compute |cpc(H)|
        cpc_H_size = count_cpc_edges(H_directed, H_bidirected)
        
        if verbose:
            print(f"\n--- Iteration {iteration} ---")
            print(f"Current bidirected edges: {current_bidirected}")
            print(f"|cpc(H)| = {cpc_H_size}")
            cpc_H = compute_confounding_paths(H_directed, H_bidirected)
            cpc_edges = [(i, j) for i in range(n) for j in range(i+1, n) if cpc_H[i, j] > 0]
            print(f"cpc(H) edges: {cpc_edges}")
            print(f"\nEvaluating each edge for removal:")
        
        # Find best bidirected edge to remove
        best_gain = 0
        e_star = None
        
        for e in current_bidirected:
            i, j = e
            # Create H \ e (remove bidirected edge)
            H_bidirected_minus_e = remove_bidirected_edge(H_bidirected, i, j)
            
            # Compute |cpc(H \ e)|
            cpc_H_minus_e_size = count_cpc_edges(H_directed, H_bidirected_minus_e)
            
            # Gain = |cpc(H)| - |cpc(H \ e)| - 1
            gain = cpc_H_size - cpc_H_minus_e_size - 1
            
            if verbose:
                cpc_minus_e = compute_confounding_paths(H_directed, H_bidirected_minus_e)
                cpc_minus_e_edges = [(ii, jj) for ii in range(n) for jj in range(ii+1, n) 
                                     if cpc_minus_e[ii, jj] > 0]
                print(f"  Edge {i}<->{j}: |cpc(H\\e)| = {cpc_H_minus_e_size}, "
                      f"gain = {cpc_H_size} - {cpc_H_minus_e_size} - 1 = {gain}")
                print(f"           cpc(H\\e) edges: {cpc_minus_e_edges}")
            
            if gain > best_gain:
                best_gain = gain
                e_star = e
        
        if verbose:
            print(f"\nBest gain = {best_gain}")
        
        if best_gain > 0:
            B_del.append(e_star)
            H_bidirected = remove_bidirected_edge(H_bidirected, e_star[0], e_star[1])
            if verbose:
                print(f"  -> Removed bidirected edge {e_star[0]} <-> {e_star[1]}")
        else:
            break
    
    # G' = G \ B_del (original graph with deleted bidirected edges removed)
    G_prime_bidirected = bidirected_adj.copy().astype(float)
    for i, j in B_del:
        G_prime_bidirected[i, j] = 0
        G_prime_bidirected[j, i] = 0
    
    # B_add = cpc(G') \ B(G')
    cpc_G_prime = compute_confounding_paths(directed_adj, G_prime_bidirected)
    
    B_add = []
    for i in range(n):
        for j in range(i + 1, n):
            # Edge is in cpc(G') but not in B(G')
            if cpc_G_prime[i, j] > 0 and G_prime_bidirected[i, j] == 0:
                B_add.append((i, j))
    
    if verbose:
        print(f"\nResult: {len(B_del)} deletions, {len(B_add)} additions")
        print(f"  B_del = {B_del}")
        print(f"  B_add = {B_add}")
    
    return B_del, B_add


def apply_confounding_path_closure(bidirected_adj: np.ndarray, 
                                    B_del: List[Tuple[int, int]], 
                                    B_add: List[Tuple[int, int]]) -> np.ndarray:
    """
    Apply confounding path closure operations to create the closed bidirected graph.
    
    Parameters:
        bidirected_adj: Original bidirected adjacency matrix
        B_del: Bidirected edges to delete
        B_add: Bidirected edges to add
    
    Returns:
        Adjacency matrix of the confounding path closed bidirected graph
    """
    result = bidirected_adj.copy()
    
    # Remove deleted edges
    for i, j in B_del:
        result[i, j] = 0
        result[j, i] = 0
    
    # Add new edges
    for i, j in B_add:
        result[i, j] = 1
        result[j, i] = 1
    
    return result


def is_confounding_path_closed(directed_adj: np.ndarray, bidirected_adj: np.ndarray) -> bool:
    """
    Check if a mixed graph's bidirected edges equal its confounding path matrix.
    
    Parameters:
        directed_adj: Adjacency matrix for directed edges
        bidirected_adj: Adjacency matrix for bidirected edges
    
    Returns:
        True if B(G) = cpc(G)
    """
    cpc = compute_confounding_paths(directed_adj, bidirected_adj)
    n = bidirected_adj.shape[0]
    
    for i in range(n):
        for j in range(n):
            if i != j:
                has_bidirected = bidirected_adj[i, j] > 0
                has_confounding = cpc[i, j] > 0
                if has_bidirected != has_confounding:
                    return False
    
    return True


def incompatibility_score(directed_adj: np.ndarray, bidirected_adj: np.ndarray, 
                         verbose: bool = False) -> Tuple[int, dict]:
    """
    Compute the incompatibility score of a mixed graph with directed and bidirected edges.
    
    The incompatibility score measures how many edge modifications are needed to transform
    the graph into a valid causal model (acyclic, transitively closed, confounding path closed).
    
    Algorithm:
    1. Run GreedyFAS on the directed part to make it acyclic (count deletions)
    2. Run GreedyTE on the acyclic graph to make it transitively closed (count deletions + additions)
    3. Add back the original bidirected edges and run GreedyCPC (count deletions + additions)
    
    Parameters:
        directed_adj: n x n adjacency matrix for directed edges (A[i,j] = 1 means i -> j)
        bidirected_adj: n x n symmetric adjacency matrix for bidirected edges
        verbose: If True, print detailed progress information
    
    Returns:
        score: Total number of edge modifications (lower is better, 0 = already compatible)
        details: Dictionary with breakdown of modifications at each step
    """
    n = directed_adj.shape[0]
    
    if verbose:
        print("=" * 60)
        print("Computing Incompatibility Score")
        print("=" * 60)
    
    # ========== Step 1: GreedyFAS to make directed part acyclic ==========
    if verbose:
        print("\n--- Step 1: GreedyFAS (make acyclic) ---")
    
    fas_edges = greedy_fas(directed_adj)
    directed_acyclic = remove_edges(directed_adj, fas_edges)
    
    fas_deletions = len(fas_edges)
    
    if verbose:
        print(f"FAS deletions: {fas_deletions}")
        if fas_edges:
            print(f"  Removed edges: {fas_edges}")
    
    # ========== Step 2: GreedyTE to make transitively closed ==========
    if verbose:
        print("\n--- Step 2: GreedyTE (make transitively closed) ---")
    
    te_E_del, te_E_add = greedy_transitivity_editing(directed_acyclic, verbose=False)
    directed_tc = apply_transitivity_editing(directed_acyclic, te_E_del, te_E_add)
    
    te_deletions = len(te_E_del)
    te_additions = len(te_E_add)
    
    if verbose:
        print(f"TE deletions: {te_deletions}, TE additions: {te_additions}")
        if te_E_del:
            print(f"  Removed edges: {te_E_del}")
        if te_E_add:
            print(f"  Added edges: {te_E_add}")
    
    # ========== Step 3: GreedyCPC with original bidirected edges ==========
    if verbose:
        print("\n--- Step 3: GreedyCPC (make confounding path closed) ---")
    
    cpc_B_del, cpc_B_add = greedy_confounding_path_closure(directed_tc, bidirected_adj, verbose=False)
    
    cpc_deletions = len(cpc_B_del)
    cpc_additions = len(cpc_B_add)
    
    if verbose:
        print(f"CPC deletions: {cpc_deletions}, CPC additions: {cpc_additions}")
        if cpc_B_del:
            print(f"  Removed bidirected edges: {cpc_B_del}")
        if cpc_B_add:
            print(f"  Added bidirected edges: {cpc_B_add}")
    
    # ========== Compute total score ==========
    total_score = fas_deletions + te_deletions + te_additions + cpc_deletions + cpc_additions
    
    details = {
        'fas_deletions': fas_deletions,
        'fas_edges': fas_edges,
        'te_deletions': te_deletions,
        'te_additions': te_additions,
        'te_E_del': te_E_del,
        'te_E_add': te_E_add,
        'cpc_deletions': cpc_deletions,
        'cpc_additions': cpc_additions,
        'cpc_B_del': cpc_B_del,
        'cpc_B_add': cpc_B_add,
        'final_directed': directed_tc,
        'final_bidirected': apply_confounding_path_closure(bidirected_adj, cpc_B_del, cpc_B_add)
    }
    
    if verbose:
        print("\n" + "=" * 60)
        print(f"TOTAL INCOMPATIBILITY SCORE: {total_score}")
        print(f"  FAS: {fas_deletions} deletions")
        print(f"  TE:  {te_deletions} deletions + {te_additions} additions = {te_deletions + te_additions}")
        print(f"  CPC: {cpc_deletions} deletions + {cpc_additions} additions = {cpc_deletions + cpc_additions}")
        print("=" * 60)
    
    return total_score, details


def visualize_confounding_path_closure(directed_adj: np.ndarray, bidirected_adj: np.ndarray,
                                        B_del: List[Tuple[int, int]], B_add: List[Tuple[int, int]],
                                        title: str = None, save_path: str = None):
    """
    Visualize the result of Greedy Confounding Path Closure.
    
    Creates a figure with three subplots:
    - Left: Original mixed graph with bidirected edges to delete highlighted in red
    - Middle: Intermediate graph after deletions
    - Right: Final confounding path closed graph with added edges in green
    
    Directed edges are shown as solid arrows, bidirected edges as dashed curved lines.
    
    Parameters:
        directed_adj: Adjacency matrix for directed edges
        bidirected_adj: Original bidirected adjacency matrix
        B_del: Bidirected edges to delete
        B_add: Bidirected edges to add
        title: Optional title for the figure
        save_path: Optional path to save the figure
    """
    n = directed_adj.shape[0]
    B_del_set = set(B_del)
    B_add_set = set(B_add)
    
    # Create figure
    fig, axes = plt.subplots(1, 3, figsize=(18, 6))
    
    # Get directed edges
    directed_edges = [(i, j) for i in range(n) for j in range(n) if directed_adj[i, j] > 0]
    
    # Get original bidirected edges (upper triangular)
    original_bidirected = [(i, j) for i in range(n) for j in range(i + 1, n) 
                           if bidirected_adj[i, j] > 0]
    kept_bidirected = [e for e in original_bidirected if e not in B_del_set]
    
    # Create graph for layout (use directed edges for positioning)
    G = nx.DiGraph()
    G.add_nodes_from(range(n))
    G.add_edges_from(directed_edges)
    pos = nx.spring_layout(G, seed=42, k=2)
    
    # ========== LEFT: Original graph ==========
    ax1 = axes[0]
    
    # Draw nodes
    nx.draw_networkx_nodes(G, pos, ax=ax1, node_color='#3498db', 
                           node_size=700, edgecolors='black', linewidths=2)
    nx.draw_networkx_labels(G, pos, ax=ax1, font_size=12, font_weight='bold')
    
    # Draw directed edges (black solid)
    nx.draw_networkx_edges(G, pos, ax=ax1, edgelist=directed_edges,
                           edge_color='black', arrows=True, arrowsize=20,
                           connectionstyle='arc3,rad=0.1')
    
    # Draw kept bidirected edges (blue dashed)
    for i, j in kept_bidirected:
        ax1.annotate("", xy=pos[j], xytext=pos[i],
                    arrowprops=dict(arrowstyle="-", color='#3498db', lw=2,
                                   linestyle='dashed', connectionstyle="arc3,rad=0.3"))
    
    # Draw deleted bidirected edges (red dashed, thicker)
    for i, j in B_del_set:
        ax1.annotate("", xy=pos[j], xytext=pos[i],
                    arrowprops=dict(arrowstyle="-", color='#e74c3c', lw=3,
                                   linestyle='dashed', connectionstyle="arc3,rad=0.3"))
    
    ax1.set_title(f'Original Graph\n({len(original_bidirected)} bidirected, red = to delete)', 
                  fontsize=12, fontweight='bold')
    ax1.axis('off')
    
    # ========== MIDDLE: After deletions ==========
    ax2 = axes[1]
    
    # Draw nodes
    nx.draw_networkx_nodes(G, pos, ax=ax2, node_color='#f39c12', 
                           node_size=700, edgecolors='black', linewidths=2)
    nx.draw_networkx_labels(G, pos, ax=ax2, font_size=12, font_weight='bold')
    
    # Draw directed edges
    nx.draw_networkx_edges(G, pos, ax=ax2, edgelist=directed_edges,
                           edge_color='black', arrows=True, arrowsize=20,
                           connectionstyle='arc3,rad=0.1')
    
    # Draw kept bidirected edges
    for i, j in kept_bidirected:
        ax2.annotate("", xy=pos[j], xytext=pos[i],
                    arrowprops=dict(arrowstyle="-", color='#3498db', lw=2,
                                   linestyle='dashed', connectionstyle="arc3,rad=0.3"))
    
    ax2.set_title(f'After Deletions\n({len(kept_bidirected)} bidirected)', 
                  fontsize=12, fontweight='bold')
    ax2.axis('off')
    
    # ========== RIGHT: Final closed graph ==========
    ax3 = axes[2]
    
