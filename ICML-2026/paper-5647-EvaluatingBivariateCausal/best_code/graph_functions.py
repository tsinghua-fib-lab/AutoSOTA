def generate_random_directed_graph(n: int, p: float, seed: int = None) -> np.ndarray:
    """
    Generate a random directed graph (possibly with cycles).
    
    Parameters:
        n: Number of vertices
        p: Probability of each directed edge
        seed: Random seed for reproducibility
    
    Returns:
        adjacency_matrix: n x n adjacency matrix where A[i,j] = 1 means edge i -> j
    """
    if seed is not None:
        np.random.seed(seed)
    
    # Sample each possible directed edge with probability p
    adjacency_matrix = (np.random.random((n, n)) < p).astype(int)
    
    # Remove self-loops
    np.fill_diagonal(adjacency_matrix, 0)
    
    return adjacency_matrix


def visualize_fas(A: np.ndarray, title: str = None, save_path: str = None):
    """
    Visualize a directed graph and highlight the Feedback Arc Set (FAS).
    
    Creates a figure with two subplots:
    - Left: Original graph with FAS edges highlighted in red
    - Right: Graph after removing FAS edges (should be acyclic)
    
    Parameters:
        A: Adjacency matrix of the directed graph
        title: Optional title for the figure
        save_path: Optional path to save the figure
    """
    n = A.shape[0]
    
    # Compute FAS
    fas = greedy_fas(A)
    fas_set = set(fas)
    
    # Create graph after removing FAS
    A_acyclic = remove_edges(A, fas)
    
    # Check if result is acyclic
    acyclic = is_acyclic(A_acyclic)
    
    # Create figure
    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    
    # ========== LEFT: Original graph with FAS highlighted ==========
    ax1 = axes[0]
    
    G_orig = nx.DiGraph()
    G_orig.add_nodes_from(range(n))
    
    # Separate edges into FAS and non-FAS
    fas_edges = []
    non_fas_edges = []
    for i in range(n):
        for j in range(n):
            if A[i, j] > 0:
                if (i, j) in fas_set:
                    fas_edges.append((i, j))
                else:
                    non_fas_edges.append((i, j))
    
    G_orig.add_edges_from(fas_edges + non_fas_edges)
    
    pos = nx.spring_layout(G_orig, seed=42, k=2)
    
    # Draw nodes
    nx.draw_networkx_nodes(G_orig, pos, ax=ax1, node_color='#3498db', 
                           node_size=700, edgecolors='black', linewidths=2)
    nx.draw_networkx_labels(G_orig, pos, ax=ax1, font_size=12, font_weight='bold')
    
    # Draw non-FAS edges (black)
    nx.draw_networkx_edges(G_orig, pos, ax=ax1, edgelist=non_fas_edges,
                           edge_color='black', arrows=True, arrowsize=20,
                           connectionstyle='arc3,rad=0.1')
    
    # Draw FAS edges (red, thicker)
    nx.draw_networkx_edges(G_orig, pos, ax=ax1, edgelist=fas_edges,
                           edge_color='#e74c3c', arrows=True, arrowsize=20,
                           width=3, connectionstyle='arc3,rad=0.1')
    
    ax1.set_title(f'Original Graph\n(Red edges = FAS, {len(fas)} edges to remove)', 
                  fontsize=12, fontweight='bold')
    ax1.axis('off')
    
    # ========== RIGHT: Graph after FAS removal ==========
    ax2 = axes[1]
    
    G_acyclic = nx.DiGraph()
    G_acyclic.add_nodes_from(range(n))
    G_acyclic.add_edges_from(non_fas_edges)
    
    # Draw nodes
    nx.draw_networkx_nodes(G_acyclic, pos, ax=ax2, node_color='#2ecc71', 
                           node_size=700, edgecolors='black', linewidths=2)
    nx.draw_networkx_labels(G_acyclic, pos, ax=ax2, font_size=12, font_weight='bold')
    
    # Draw remaining edges
    nx.draw_networkx_edges(G_acyclic, pos, ax=ax2, edgelist=non_fas_edges,
                           edge_color='black', arrows=True, arrowsize=20,
                           connectionstyle='arc3,rad=0.1')
    
    status = "Acyclic" if acyclic else "Still has cycles!"
    ax2.set_title(f'After FAS Removal\n({status}, {len(non_fas_edges)} edges remaining)', 
                  fontsize=12, fontweight='bold')
    ax2.axis('off')
    
    # Legend
    from matplotlib.patches import Patch
    from matplotlib.lines import Line2D
    legend_elements = [
        Line2D([0], [0], color='black', lw=2, label='Kept edges'),
        Line2D([0], [0], color='#e74c3c', lw=3, label='FAS edges (removed)')
    ]
    fig.legend(handles=legend_elements, loc='lower center', ncol=2, fontsize=11,
               bbox_to_anchor=(0.5, -0.02))
    
    if title:
        fig.suptitle(title, fontsize=14, fontweight='bold', y=1.02)
    
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight')
        print(f"Figure saved to: {save_path}")
    
    plt.show()
    
    return fig, fas


